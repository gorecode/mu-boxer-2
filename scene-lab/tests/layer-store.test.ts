import assert from 'node:assert/strict';
import test from 'node:test';
import { LayerStore } from '../src/experiments/layers/store.ts';

test('layer lifecycle blocks playback until each connection loads successfully', () => {
  let now = 100;
  const store = new LayerStore('', () => now);
  store.toggle();
  assert.equal(store.playing, false);
  store.connect();
  store.toggle();
  assert.equal(store.ready, false);
  assert.equal(store.playing, false);
  store.imageReady();
  store.toggle();
  now += 200;
  store.tick(now);
  assert.equal(store.time, 200);
  store.disconnect();
  store.imageReady();
  store.toggle();
  assert.equal(store.ready, false);
  assert.equal(store.playing, false);
  store.connect();
  store.toggle();
  assert.equal(store.playing, false);
  store.imageFailed();
  store.toggle();
  assert.equal(store.ready, false);
  assert.equal(store.playing, false);
  assert.match(store.status, /Обновите/);
  store.disconnect();
  store.connect();
  store.imageReady();
  store.toggle();
  assert.equal(store.playing, true);
  assert.equal(store.time, 200);
  store.imageFailed();
  assert.equal(store.playing, false);
  assert.equal(store.ready, false);
  store.disconnect();
  store.disconnect();
});

test('layer settings survive reconnect without creating playable disconnected state', () => {
  const store = new LayerStore('?engine=native&lead=1300', () => 0);
  store.setRate(2);
  store.seek(3000);
  store.setLead(800);
  store.setEngine('gsap');
  store.setReduced(true);
  assert.equal(store.ready, false);
  store.connect();
  store.imageReady();
  store.connect();
  assert.equal(store.ready, true);
  assert.equal(store.time, 3000);
  assert.equal(store.rate, 2);
  assert.equal(store.engine, 'gsap');
  assert.equal(store.reduced, true);
  store.disconnect();
});
