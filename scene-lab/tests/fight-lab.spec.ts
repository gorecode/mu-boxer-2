import { readFile } from 'node:fs/promises';
import { expect, test, type Page } from '@playwright/test';
async function begin(page: Page): Promise<void> {
  await page.clock.install({ time: new Date('2026-11-20T09:00:00Z') });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('./fight.html'); await expect(page.locator('#start')).toHaveText('НАЧАТЬ БОЙ →');
  await page.clock.pauseAt(new Date('2026-11-20T10:00:00Z'));
  await page.getByRole('checkbox', { name: 'ТРЕНИРОВКА', exact: true }).check();
  await page.locator('#start').click(); await page.clock.runFor(1800);
  await expect(page.locator('#arena')).toHaveAttribute('data-training', 'true');
}
const num = async (page: Page, key: string) => Number(await page.locator('#arena').getAttribute(`data-${key}`));

test('training freezes, steps exactly once, restores detached moments and slows the simulation', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await begin(page); const arena = page.locator('#arena');
  await page.locator('#training-panel summary').focus(); await page.keyboard.press('Space');
  await expect(page.locator('#training-panel')).toHaveJSProperty('open', false);
  await page.keyboard.press('Space'); await expect(page.locator('#training-panel')).toHaveJSProperty('open', true);
  await page.clock.runFor(100); expect(await num(page, 'player-y')).toBe(0);
  await expect(page.locator('#training-load')).toBeDisabled();
  await page.locator('#training-dummy').selectOption('guard');
  await page.locator('#training-freeze').click(); const time = await num(page, 'time');
  await page.clock.runFor(1000); expect(await num(page, 'time')).toBe(time);
  await page.keyboard.press('j'); await page.locator('#training-step').click();
  expect(await num(page, 'time')).toBeCloseTo(time + 1/120, 8);
  await expect(arena).toHaveAttribute('data-player-action', 'jab');
  await page.locator('#training-step').click(); const savedTime = await num(page, 'time'), savedAction = await num(page, 'player-action-time');
  await page.locator('#training-save').click(); await expect(page.locator('#training-load')).toBeEnabled();
  const x = await num(page, 'player-x'); await page.locator('#training-freeze').click();
  await page.keyboard.down('d'); await page.clock.runFor(1100); await page.keyboard.up('d');
  expect(await num(page, 'player-x')).toBeGreaterThan(x + 100);
  await page.locator('#training-dummy').selectOption('idle');
  await page.keyboard.down('d'); await page.locator('#training-load').click(); await page.keyboard.up('d');
  await expect(page.locator('#training-dummy')).toHaveValue('guard');
  expect(await num(page, 'time')).toBe(savedTime); expect(await num(page, 'player-x')).toBe(x);
  expect(await num(page, 'player-action-time')).toBe(savedAction); await expect(arena).toHaveAttribute('data-frozen', 'true');
  await page.locator('#training-freeze').click(); await page.clock.runFor(700); expect(await num(page, 'player-x')).toBe(x);
  await page.locator('#training-speed').selectOption('0.25'); const before = await num(page, 'time');
  await arena.focus(); await page.keyboard.down('d'); await page.clock.runFor(400); await page.keyboard.up('d');
  expect(await num(page, 'time') - before).toBeCloseTo(.1, 2);
  expect(await num(page, 'player-x') - x).toBeGreaterThan(25); expect(await num(page, 'player-x') - x).toBeLessThan(45);
  await expect(page.locator('#timer')).toHaveText('90');
  await page.getByRole('checkbox', { name: 'ТРЕНИРОВКА', exact: true }).uncheck();
  await expect(page.locator('#training-panel')).toBeHidden(); await page.clock.runFor(1900);
  await expect(arena).toHaveAttribute('data-training', 'false'); expect(await num(page, 'time')).toBeGreaterThan(.2);
  expect(errors).toEqual([]);
});

